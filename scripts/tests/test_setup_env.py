"""Tests for scripts/setup-env.py in a throwaway repo layout; never touches the real .env."""

import io
import re
import stat

import pytest
from conftest import load_script
from localenv_stubs import Sandbox

SCRIPT = "setup-env.py"
mod = load_script(SCRIPT)

HEX_A = "a" * 64
HEX_MIXED = "AbC1" * 16
KEYS = [
    "POSTGRES_PASSWORD",
    "SEED_USER_ID",
    "JWT_SECRET",
    "CONFIG_SECRETS_ENCRYPTION_KEY",
    "BROKER_ACCOUNTS_ENCRYPTION_KEY",
]
# Interactive answers: postgres (default), seed (default), JWT choice, OTLP endpoint, OTLP headers.
ANSWERS = "\n\n1\nhttps://otlp.example/otlp\nBasic abc=\n"


@pytest.fixture
def box(tmp_path):
    return Sandbox(tmp_path, SCRIPT)


def assignments(path):
    """Ordered (name, value) pairs of the non-comment lines, single quotes stripped."""
    pairs = []
    for line in path.read_text().splitlines():
        if line and not line.startswith("#"):
            name, value = line.split("=", 1)
            assert value[0] == value[-1] == "'"
            pairs.append((name, value[1:-1]))
    return pairs


def mode(path):
    return stat.S_IMODE(path.stat().st_mode)


@pytest.mark.parametrize(
    "text,expected",
    [
        (f"K={HEX_A}\n", HEX_A),
        (f"K='{HEX_A}'\n", HEX_A),
        (f'K="{HEX_MIXED}"\n', HEX_MIXED),
        (f"K={'b' * 64}\nOTHER=1\nK={HEX_A}\n", HEX_A),
        (f"K={HEX_A}\nK=short\n", ""),
        (f"K={HEX_A}0\n", ""),
        (f"K={'g' * 64}\n", ""),
        (f"K={HEX_A}\r\n", ""),
        (f" K={HEX_A}\n", ""),
        (f"KK={HEX_A}\n", ""),
        ("", ""),
    ],
)
def test_existing_hex_key(text, expected):
    assert mod.existing_hex_key("K", text) == expected


def test_render_env_omits_empty_otel_values():
    values = dict.fromkeys(KEYS, "v") | {
        "OTEL_EXPORTER_OTLP_ENDPOINT": "",
        "OTEL_EXPORTER_OTLP_HEADERS": "h",
    }
    text = mod.render_env(values)
    assert "OTEL_EXPORTER_OTLP_ENDPOINT=" not in text
    assert "\nOTEL_EXPORTER_OTLP_HEADERS='h'\n\n# ════" in text
    assert text.startswith(
        "# xstockstrat — Environment Variables\n# Generated by scripts/setup-env.py\n"
    )
    assert text.endswith("# See: docs/setup/digitalocean.md Step 9\n")


def test_read_line_trims_blanks(monkeypatch):
    monkeypatch.setattr(mod.sys, "stdin", io.StringIO(" \tvalue with space \t\nnext\n"))
    assert mod.read_line() == "value with space"
    assert mod.read_line(silent=True) == "next"


@pytest.mark.parametrize("text", ["", "partial"])
def test_read_line_exits_when_stdin_is_closed(monkeypatch, text):
    monkeypatch.setattr(mod.sys, "stdin", io.StringIO(text))
    with pytest.raises(SystemExit) as exc:
        mod.read_line()
    assert exc.value.code == 1


def test_defaults_on_a_fresh_checkout(box):
    result = box.run(SCRIPT, "--defaults")
    env = box.root / ".env"
    assert result.returncode == 0 and result.stderr == ""
    assert mode(env) == 0o644
    pairs = assignments(env)
    assert [name for name, _ in pairs] == KEYS
    values = dict(pairs)
    assert values["POSTGRES_PASSWORD"] == "devpassword"
    assert values["SEED_USER_ID"] == "80880990-2b79-4d85-8761-d8d9102c2efb"
    assert re.fullmatch(r"[0-9a-f]{32}", values["JWT_SECRET"])
    assert re.fullmatch(r"[0-9a-f]{64}", values["CONFIG_SECRETS_ENCRYPTION_KEY"])
    assert re.fullmatch(r"[0-9a-f]{64}", values["BROKER_ACCOUNTS_ENCRYPTION_KEY"])
    assert (
        values["CONFIG_SECRETS_ENCRYPTION_KEY"]
        != values["BROKER_ACCOUNTS_ENCRYPTION_KEY"]
    )
    text = env.read_text()
    assert "ALPACA_API_KEY=" not in text and "MCP_AGENT_SECRET=" not in text
    for secret in ("JWT_SECRET", *KEYS[3:]):
        assert values[secret] not in result.stdout
    assert "Generated JWT_SECRET (non-interactive mode)" in result.stdout
    assert "Generated CONFIG_SECRETS_ENCRYPTION_KEY" in result.stdout
    assert f"Location: {env}" in result.stdout
    assert "   python3 scripts/bootstrap.py\n" in result.stdout
    assert "OTEL_EXPORTER_OTLP" not in result.stdout.split("Configuration Summary")[1]


def test_rerun_keeps_valid_encryption_keys_and_overwrites_the_rest(box):
    env = box.root / ".env"
    env.write_text(
        "POSTGRES_PASSWORD='custom'\nJWT_SECRET='old-jwt'\nEXTRA=1\n"
        f"CONFIG_SECRETS_ENCRYPTION_KEY='{HEX_A}'\n"
        f'CONFIG_SECRETS_ENCRYPTION_KEY="{HEX_MIXED}"\n'
        "BROKER_ACCOUNTS_ENCRYPTION_KEY='tooshort'\n"
    )
    env.chmod(0o600)
    result = box.run(SCRIPT, "--defaults")
    assert result.returncode == 0
    assert ".env already exists. Continuing will overwrite it." in result.stdout
    assert "Kept existing CONFIG_SECRETS_ENCRYPTION_KEY" in result.stdout
    assert "Generated BROKER_ACCOUNTS_ENCRYPTION_KEY" in result.stdout
    assert mode(env) == 0o600
    pairs = assignments(env)
    assert [name for name, _ in pairs] == KEYS
    values = dict(pairs)
    assert values["CONFIG_SECRETS_ENCRYPTION_KEY"] == HEX_MIXED
    assert re.fullmatch(r"[0-9a-f]{64}", values["BROKER_ACCOUNTS_ENCRYPTION_KEY"])
    assert values["POSTGRES_PASSWORD"] == "devpassword"
    assert values["JWT_SECRET"] != "old-jwt"
    assert HEX_MIXED not in result.stdout


def test_skip_leaves_an_existing_env_untouched(box):
    env = box.root / ".env"
    env.write_text("X=1\n")
    result = box.run(SCRIPT, "--skip")
    assert result.returncode == 0
    assert (
        result.stdout
        == "\033[0;32m[OK]\033[0m    .env already exists — skipping setup.\n"
    )
    assert env.read_text() == "X=1\n"


def test_skip_is_honoured_only_as_the_first_argument(box):
    env = box.root / ".env"
    env.write_text("X=1\n")
    assert box.run(SCRIPT, "--defaults", "--skip").returncode == 0
    assert [name for name, _ in assignments(env)] == KEYS


def test_skip_without_an_env_runs_the_setup(box):
    assert box.run(SCRIPT, "--skip", "--defaults").returncode == 0
    assert (box.root / ".env").is_file()


def test_unknown_flag(box):
    result = box.run(SCRIPT, "--defaults", "--nope")
    assert result.returncode == 1
    assert result.stderr == "\033[0;31m[ERROR]\033[0m Unknown flag: --nope\n"
    assert not (box.root / ".env").exists()


@pytest.mark.parametrize("var", ["CI", "GITHUB_ACTIONS"])
def test_refuses_to_run_in_ci(box, var):
    result = box.run(SCRIPT, "--defaults", env={var: "true"})
    assert result.returncode == 1 and result.stdout == ""
    assert "This script is for local development only." in result.stderr
    assert not (box.root / ".env").exists()


def test_interactive_with_a_generated_jwt_secret(box):
    result = box.run(SCRIPT, stdin=ANSWERS)
    assert result.returncode == 0 and result.stderr == ""
    pairs = assignments(box.root / ".env")
    assert [name for name, _ in pairs] == [
        *KEYS,
        "OTEL_EXPORTER_OTLP_ENDPOINT",
        "OTEL_EXPORTER_OTLP_HEADERS",
    ]
    values = dict(pairs)
    assert values["POSTGRES_PASSWORD"] == "devpassword"
    assert re.fullmatch(r"[0-9a-f]{32}", values["JWT_SECRET"])
    assert values["OTEL_EXPORTER_OTLP_ENDPOINT"] == "https://otlp.example/otlp"
    assert values["OTEL_EXPORTER_OTLP_HEADERS"] == "Basic abc="
    assert "\033[1mPOSTGRES_PASSWORD\033[0m\n" in result.stdout
    # The default line shows the colour codes unexpanded, as the shell version always did.
    assert "  Default: \\033[0;36mdevpassword\\033[0m\n  → (hidden) \n" in result.stdout
    assert "Generated secure JWT_SECRET" in result.stdout
    assert "✓ OTEL_EXPORTER_OTLP_ENDPOINT (observability — optional)" in result.stdout
    assert "Basic abc=" not in result.stdout


def test_interactive_with_typed_values(box):
    answers = "pg pass\n  11111111-1111-1111-1111-111111111111\t\n2\nown-jwt-secret\nhttp://e\nhdr\n"
    result = box.run(SCRIPT, stdin=answers)
    assert result.returncode == 0
    values = dict(assignments(box.root / ".env"))
    assert values["POSTGRES_PASSWORD"] == "pg pass"
    assert values["SEED_USER_ID"] == "11111111-1111-1111-1111-111111111111"
    assert values["JWT_SECRET"] == "own-jwt-secret"
    for typed in ("pg pass", "own-jwt-secret", "hdr"):
        assert typed not in result.stdout


def test_a_value_without_a_default_cannot_be_left_empty(box):
    result = box.run(SCRIPT, stdin="\n\n2\n\n\nown-jwt\nhttp://e\nhdr\n")
    assert result.returncode == 0
    assert result.stderr == "\033[0;31m[ERROR]\033[0m This value cannot be empty.\n" * 2
    assert dict(assignments(box.root / ".env"))["JWT_SECRET"] == "own-jwt"


@pytest.mark.parametrize("answers", ["", "\n\n", "\n\n1\nhttp://e\npartial"])
def test_closed_stdin_aborts_without_writing(box, answers):
    result = box.run(SCRIPT, stdin=answers)
    assert result.returncode == 1 and result.stderr == ""
    assert not (box.root / ".env").exists()
