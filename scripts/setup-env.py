#!/usr/bin/env python3
"""Interactive .env setup for local xstockstrat development.

Usage:
  python3 scripts/setup-env.py            # interactive mode
  python3 scripts/setup-env.py --defaults # use all defaults (devpassword, etc.)
  python3 scripts/setup-env.py --skip     # skip if .env exists (honoured as the first argument only)

Writes <repo>/.env (secrets only; an existing file is overwritten, keeping its 64-hex encryption keys).
Exit 0 = .env written, or kept by --skip; 1 = CI environment, unknown flag, or stdin closed at a prompt.
"""

import functools
import os
import re
import secrets
import sys

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ENV_FILE = os.path.join(REPO_ROOT, ".env")

RED = "\033[0;31m"
GREEN = "\033[0;32m"
YELLOW = "\033[1;33m"
CYAN = "\033[0;36m"
BOLD = "\033[1m"
NC = "\033[0m"

echo = functools.partial(print, flush=True)


def info(text=""):
    echo(f"{CYAN}[INFO]{NC}  {text}")


def ok(text):
    echo(f"{GREEN}[OK]{NC}    {text}")


def warn(text):
    echo(f"{YELLOW}[WARN]{NC}  {text}")


def err(text):
    print(f"{RED}[ERROR]{NC} {text}", file=sys.stderr, flush=True)


def section(text):
    echo(f"\n{BOLD}{CYAN}===> {text}{NC}")


def read_line(silent=False):
    """One line from stdin, blanks trimmed; a closed stdin exits 1. `silent` hides typing on a terminal."""
    if silent and sys.stdin.isatty():
        import termios

        fd = sys.stdin.fileno()
        saved = termios.tcgetattr(fd)
        hidden = termios.tcgetattr(fd)
        hidden[3] &= ~termios.ECHO
        termios.tcsetattr(fd, termios.TCSADRAIN, hidden)
        try:
            line = sys.stdin.readline()
        finally:
            termios.tcsetattr(fd, termios.TCSADRAIN, saved)
    else:
        line = sys.stdin.readline()
    if not line.endswith("\n"):
        sys.exit(1)
    return line[:-1].strip(" \t")


def prompt_value(name, default, description, secret=False, use_defaults=False):
    if use_defaults:
        return default

    echo()
    echo(f"{BOLD}{name}{NC}")
    echo(f"  {description}")
    if default:
        echo(rf"  Default: \033[0;36m{default}\033[0m")

    prompt_char = "→ (hidden)" if secret else "→"
    while True:
        echo(f"  {prompt_char} ", end="")
        value = read_line(silent=secret)
        if secret:
            echo()
        value = value or default
        if value:
            return value
        err("This value cannot be empty.")


def existing_hex_key(name, env_text):
    """NAME's value from the current .env text when it is 64 hex chars, else ''."""
    values = [
        line.split("=", 1)[1]
        for line in env_text.split("\n")
        if line.startswith(f"{name}=")
    ]
    if not values:
        return ""
    value = values[-1].replace("'", "").replace('"', "")
    return value if re.fullmatch(r"[0-9a-fA-F]{64}", value) else ""


def render_env(values):
    """The .env text; `values` maps each variable to its value, empty OTEL values are left out."""
    otel = "".join(
        f"{name}='{values[name]}'\n"
        for name in ("OTEL_EXPORTER_OTLP_ENDPOINT", "OTEL_EXPORTER_OTLP_HEADERS")
        if values[name]
    )
    return f"""\
# xstockstrat — Environment Variables
# Generated by scripts/setup-env.py
# ⚠️  NEVER commit this file to git — it contains secrets!

# ── Database ───────────────────────────────────────────────────────────────
# Local dev only. In production, DATABASE_URL is injected by DigitalOcean App Platform.
POSTGRES_PASSWORD='{values["POSTGRES_PASSWORD"]}'
SEED_USER_ID='{values["SEED_USER_ID"]}'

# Vendor credentials (Alpaca, FMP, Finnhub) are not env vars: they are encrypted config rows
# resolved by xstockstrat-marketdata via GetSecret (feature 147). Set them through config.

# ── JWT (xstockstrat-identity, xstockstrat-ui, xstockstrat-agent) ─────
# Signs/verifies auth tokens; the agent also HMAC-signs its OAuth 2.1 txn blob with it.
JWT_SECRET='{values["JWT_SECRET"]}'

# ── Encryption Keys (xstockstrat-config, xstockstrat-trading) ──────────
# AES-256, 64 hex chars (openssl rand -hex 32). Rotating one orphans rows encrypted under it.
CONFIG_SECRETS_ENCRYPTION_KEY='{values["CONFIG_SECRETS_ENCRYPTION_KEY"]}'
BROKER_ACCOUNTS_ENCRYPTION_KEY='{values["BROKER_ACCOUNTS_ENCRYPTION_KEY"]}'

# ── OpenTelemetry (Optional) ────────────────────────────────────────────
# Leave empty to disable. Enable for Grafana Cloud observability.
{otel}
# ═════════════════════════════════════════════════════════════════════════
# GitHub Repository Secrets (NOT local .env — set in GitHub only)
# ═════════════════════════════════════════════════════════════════════════
# These variables must be added as repository secrets in GitHub:
# Settings → Secrets and variables → Actions
#
# Secret Name               Used by workflow            How to obtain
# ─────────────────────────────────────────────────────────────────────
# DIGITALOCEAN_ACCESS_TOKEN deploy-dev / deploy-prod    DigitalOcean API PAT
# SOPS_AGE_KEY (env secret) deploy-* / prod-up / bootstrap  age-keygen (docs/runbooks/sops-secrets.md)
# BUF_TOKEN                 deploy-dev / deploy-prod    buf.build → Settings → Tokens
# GH_PAT_SCAN               ci (secret-scan)            GitHub PAT with repo read
#
# GITHUB_TOKEN is automatically provided by GitHub Actions — no setup needed.
# See: docs/setup/digitalocean.md Step 9
"""


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv

    if os.environ.get("CI") or os.environ.get("GITHUB_ACTIONS"):
        err("This script is for local development only.")
        err("In CI environments, secrets are injected via GitHub Actions.")
        err("See: .github/workflows/ci.yml")
        return 1

    if os.path.isfile(ENV_FILE):
        if argv[:1] == ["--skip"]:
            ok(".env already exists — skipping setup.")
            return 0
        warn(".env already exists. Continuing will overwrite it.")

    use_defaults = False
    for arg in argv:
        if arg == "--defaults":
            use_defaults = True
        elif arg != "--skip":
            err(f"Unknown flag: {arg}")
            return 1

    prompt = functools.partial(prompt_value, use_defaults=use_defaults)
    values = {}

    section("xstockstrat — Environment Setup")

    info("This script will create a .env file for local development.")
    info("Three-file convention:")
    info(
        "  • .env — NOT committed; secrets only (POSTGRES_PASSWORD, JWT_SECRET, encryption keys)"
    )
    info(
        "  • .env.local — committed; structural config (APPLICATION_ENV, NODE_ENV, etc.)"
    )
    info("  • .env.fe.local — committed; frontend-only config (APP_URL)")
    info()
    info("You only need to configure .env. The other two are pre-populated.")
    info()

    section("Database")

    values["POSTGRES_PASSWORD"] = prompt(
        "POSTGRES_PASSWORD",
        "devpassword",
        "PostgreSQL password for local development.\n"
        "  docker-compose will construct DATABASE_URL automatically.\n"
        "  Use 'devpassword' for local dev; ignore for production (managed DB).",
        secret=True,
    )

    values["SEED_USER_ID"] = prompt(
        "SEED_USER_ID",
        "80880990-2b79-4d85-8761-d8d9102c2efb",
        "Existing user id that pre-existing strategies are assigned to at migration time\n"
        "  (feature 133, migration 013's ownership backfill). Only matters when the local DB\n"
        "  already has strategies; the shown default is safe for a fresh local DB.",
    )

    section("JWT Secret")

    info(
        "Used by xstockstrat-identity for signing and verifying authentication tokens, and by"
    )
    info("xstockstrat-agent to HMAC-sign its OAuth 2.1 txn blob.")
    info()

    if use_defaults:
        values["JWT_SECRET"] = secrets.token_hex(16)
        info("Generated JWT_SECRET (non-interactive mode)")
    else:
        echo("Would you like to:")
        echo("  1) Generate a secure random secret automatically")
        echo("  2) Provide your own")
        echo()
        echo("  → ", end="")
        if read_line() == "1":
            values["JWT_SECRET"] = secrets.token_hex(16)
            ok("Generated secure JWT_SECRET")
        else:
            values["JWT_SECRET"] = prompt(
                "JWT_SECRET",
                "",
                "Your JWT secret (minimum 32 characters recommended).",
                secret=True,
            )

    section("Encryption Keys")

    info("AES-256 master keys (64 hex chars) required by docker-compose:")
    info(
        "  • CONFIG_SECRETS_ENCRYPTION_KEY  — xstockstrat-config secret rows (vendor credentials)"
    )
    info("  • BROKER_ACCOUNTS_ENCRYPTION_KEY — xstockstrat-trading broker credentials")
    info(
        "Keys already in .env are kept: a new key cannot decrypt rows written under the old one."
    )
    info()

    env_text = ""
    if os.path.isfile(ENV_FILE):
        with open(
            ENV_FILE, encoding="utf-8", errors="surrogateescape", newline=""
        ) as f:
            env_text = f.read()
    for name in ("CONFIG_SECRETS_ENCRYPTION_KEY", "BROKER_ACCOUNTS_ENCRYPTION_KEY"):
        values[name] = existing_hex_key(name, env_text)
        if values[name]:
            ok(f"Kept existing {name}")
        else:
            values[name] = secrets.token_hex(32)
            ok(f"Generated {name}")

    section("OpenTelemetry / Grafana Cloud (Optional)")

    info("For local dev, OpenTelemetry is optional. Services work fine without it.")
    info("If you want to enable observability (traces):")
    info()
    info("  1. Create a Grafana Cloud account: https://grafana.com/products/cloud/")
    info("  2. Create an OTLP token in Grafana Cloud")
    info("  3. Paste the token and endpoint here")
    info()
    info("To skip: just press Enter to leave empty.")
    info("Setup details: docs/setup/grafana-cloud.md")
    info()

    values["OTEL_EXPORTER_OTLP_ENDPOINT"] = prompt(
        "OTEL_EXPORTER_OTLP_ENDPOINT",
        "",
        "Grafana Cloud OTLP endpoint URL (e.g. https://otlp-gateway-<region>.grafana.net/otlp).",
    )

    values["OTEL_EXPORTER_OTLP_HEADERS"] = prompt(
        "OTEL_EXPORTER_OTLP_HEADERS",
        "",
        "Grafana Cloud OTLP auth header value (Basic <base64(instanceId:apiKey)>"
        " — see docs/setup/grafana-cloud.md).",
        secret=True,
    )

    section("Writing .env file")

    with open(ENV_FILE, "w", encoding="utf-8", errors="surrogateescape") as f:
        f.write(render_env(values))

    ok(".env created successfully")
    ok(f"Location: {ENV_FILE}")

    section("Configuration Summary")

    echo()
    echo("✓ POSTGRES_PASSWORD     (database — local dev only)")
    echo("✓ JWT_SECRET            (authentication tokens, agent OAuth txn signing)")
    echo("✓ CONFIG_SECRETS_ENCRYPTION_KEY  (config secrets at rest)")
    echo("✓ BROKER_ACCOUNTS_ENCRYPTION_KEY (broker credentials at rest)")
    if values["OTEL_EXPORTER_OTLP_ENDPOINT"]:
        echo("✓ OTEL_EXPORTER_OTLP_ENDPOINT (observability — optional)")
    if values["OTEL_EXPORTER_OTLP_HEADERS"]:
        echo("✓ OTEL_EXPORTER_OTLP_HEADERS  (observability — optional)")

    echo()
    section("Next Steps")

    echo()
    echo("1. Verify the .env file:")
    echo("   cat .env")
    echo()
    echo("2. Bootstrap the environment:")
    echo("   python3 scripts/bootstrap.py")
    echo()
    echo("   This will:")
    echo("   • Generate proto stubs (in Docker)")
    echo("   • Install Node.js dependencies (if pnpm is installed)")
    echo("   • Install Python dependencies (if python3 is installed)")
    echo()
    echo("3. Start all services:")
    echo("   docker compose up -d")
    echo()
    echo("4. Verify services are healthy:")
    echo("   docker compose ps")
    echo()
    echo("5. Check out a specific service:")
    echo("   curl -s http://localhost:8060/health    # config service")
    echo("   curl -s http://localhost:8058/health    # identity service")
    echo()
    echo("Docs:")
    echo("  Getting Started:  docs/setup/getting-started.md")
    echo("  Alpaca Setup:     docs/setup/alpaca.md")
    echo("  Full Architecture: CLAUDE.md")
    echo()
    ok("Setup ready! Run bootstrap.py to continue.")
    echo()
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except KeyboardInterrupt:
        sys.exit(130)
